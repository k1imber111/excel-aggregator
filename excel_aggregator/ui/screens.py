"""Статические экраны: главное меню и инструкция."""

from __future__ import annotations

from rich.panel import Panel

from .nav import Command
from .widgets import UI

INSTRUCTION = """\
[bold]Для чего нужна программа[/]

У вас есть несколько файлов Excel с таблицами. В каждой таблице есть общий
столбец (или строка) с названиями объектов — по ним таблицы можно связать.
Программа находит каждый объект во всех файлах и собирает его характеристики
из разных таблиц в один итоговый файл: каждый объект — одна строка, каждая
характеристика — отдельный столбец.

[bold]Как работать с программой[/]

[cyan]Шаг 1.[/] Укажите путь к первому файлу Excel (.xls или .xlsx).
  Путь можно перетащить мышью в окно консоли или вставить из буфера —
  кавычки программа уберёт сама. После загрузки программа покажет
  первые строки файла, чтобы вы убедились, что файл открыт верно.

[cyan]Шаг 2.[/] Если в файле несколько листов — выберите нужные
  (можно несколько, номера через запятую).

[cyan]Шаг 3.[/] Укажите, где начинаются названия объектов: координату
  первой ячейки в формате Excel (например, A6) и как читать значения —
  сверху вниз (вертикально) или слева направо (горизонтально).
  Программа дочитает значения до конца таблицы, пропуская пустые ячейки,
  и покажет, сколько названий найдено, и первые пять из них.

[cyan]Шаг 4.[/] Выберите столбцы с характеристиками, которые нужно
  перенести в итоговый файл (можно несколько). Названия столбцов
  программа прочитает из заголовков таблицы автоматически; если
  заголовок прочитать не удастся — попросит ввести название.

[cyan]Шаг 5.[/] Добавьте остальные файлы по очереди. В каждом новом
  файле программа сама ищет столбец с названиями объектов и показывает
  лучший вариант: вам остаётся подтвердить его, посмотреть следующий
  вариант или указать координаты вручную. Затем выберите столбцы
  с характеристиками — как на шаге 4.

[cyan]Шаг 6.[/] Нажмите «Собрать файл». Программа запишет итоговую
  таблицу в новый файл Excel: все названия объектов из всех файлов
  и их характеристики — каждая в отдельном столбце, оформленные
  в аккуратную таблицу.

[bold]Навигация на каждом шаге[/]

  [green]н[/] — вернуться к предыдущему шагу;
  [green]с[/] — собрать файл (когда настроен хотя бы один источник);
  [green]о[/] — отменить настройку и выйти в главное меню.

  Когда программа просит ввести название столбца, команды пишутся целым
  словом: [green]назад[/], [green]собрать[/], [green]отмена[/] — чтобы
  столбец можно было назвать одной буквой (Y, Н, С).

[bold]Полезно знать[/]

  • Объединённые ячейки, разные шрифты и форматы ячеек не мешают:
    программа читает значения.
  • Если в одном файле название записано числом, а в другом — текстом,
    программа всё равно их сопоставит.
  • Исходные файлы не изменяются — программа только читает их.
  • Лишние пробелы и переносы строк внутри названий объектов не мешают
    сопоставлению.
  • Если на каком-то шаге случится непредвиденная ошибка, настройка
    не пропадёт: программа предложит повторить шаг, а подробности
    запишет в файл aggregator_error.log рядом с собой.
"""


def show_instruction(ui: UI) -> None:
    """Экран «Инструкция»."""
    ui.screen("Инструкция")
    ui.console.print(Panel(INSTRUCTION, border_style="cyan", padding=(1, 2)))
    ui.console.input("[dim]Нажмите Enter, чтобы вернуться в меню...[/]")


def main_menu(ui: UI) -> int | Command:
    """Главное меню -> 0 (инструкция), 1 (запуск) или Command."""
    ui.screen()
    return ui.choose(
        "Главное меню",
        ["Инструкция", "Запуск программы", "Выход"],
        allow_back=False,
    )
