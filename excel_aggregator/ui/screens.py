"""Статические экраны: главное меню и инструкция."""

from __future__ import annotations

from rich.panel import Panel

from .nav import Command
from .widgets import UI

INSTRUCTION = """\
[bold]Для чего нужна программа[/]

У вас есть несколько файлов Excel с таблицами об одних и тех же объектах.
В каждой таблице есть столбец с названиями (номерами, кодами) объектов,
а рядом — разные характеристики. Программа находит каждый объект во всех
файлах и собирает его характеристики в одну общую таблицу: каждый объект —
одна строка, каждая характеристика — отдельный столбец.

[bold]Что нужно от вас[/]

Только указать файлы и подтвердить то, что программа нашла. Шапку таблицы,
начало данных и столбец с названиями объектов программа определяет сама —
даже если шапка занимает несколько строк и в ней есть объединённые ячейки.

[bold]Как работать[/]

[cyan]Шаг 1. Файлы.[/] Укажите путь к файлу Excel (.xls или .xlsx) и нажмите
  Enter. Повторите для остальных файлов. Можно указать папку — программа
  возьмёт из неё все таблицы. Путь удобно перетащить мышью в окно программы.
  Когда все файлы добавлены, нажмите Enter на пустой строке.

[cyan]Шаг 2. Проверка.[/] Программа покажет, что нашла в каждом файле: лист,
  строки шапки, строки данных, столбец с названиями объектов, сколько
  названий найдено и сколько из них общих с другими таблицами. Ниже — первые
  и последние названия. Если всё верно, нажмите Enter. Если программа
  ошиблась — выберите «Изменить источник» и поправьте: первую строку данных,
  столбец названий, другой лист.

[cyan]Шаг 3. Столбцы.[/] Для каждой таблицы программа покажет список столбцов
  с полными названиями. Нажмите Enter, чтобы перенести все, или введите
  номера нужных: [green]2,4[/], [green]2-5[/], [green]кроме: 3[/].

[cyan]Сборка.[/] Нажмите Enter — файл «Агрегированная таблица.xlsx» появится
  рядом с программой — или введите своё имя. Программа запишет таблицу,
  перечитает её для проверки и покажет отчёт.

[bold]Что получится[/]

Файл Excel с названием таблицы, шапкой как в исходных файлах (над каждым
блоком столбцов — имя файла, откуда он взят), фильтрами на нижней строке
шапки, закреплённой шапкой и первым столбцом, подобранной шириной столбцов.

[bold]Навигация на каждом шаге[/]

  [green]н[/] — вернуться к предыдущему шагу;
  [green]с[/] — сразу собрать файл (когда таблицы уже найдены);
  [green]о[/] — отменить работу и выйти в главное меню.

[bold]Как программа бережёт точность[/]

  • Числа, записанные текстом, и текст, записанный числом, сопоставляются;
    лишние пробелы и переносы строк в названиях не мешают.
  • Строки-подписи («район 2», «Итого», «Примечание») объектами не считаются.
  • О повторах названий, ячейках с ошибками (#REF!) и малом числе совпадений
    программа предупреждает.
  • Если названия отличаются только латинскими и русскими буквами (A и А),
    программа спросит, считать ли их одним объектом.
  • После записи файл перечитывается и сверяется с исходными данными.
  • Исходные файлы не изменяются — программа только читает их.
  • При непредвиденной ошибке настройка не пропадает: программа предложит
    повторить шаг, а подробности запишет в файл aggregator_error.log.
"""


def show_instruction(ui: UI) -> None:
    """Экран «Инструкция»."""
    ui.screen("Инструкция")
    ui.console.print(Panel(INSTRUCTION, border_style="cyan", padding=(1, 2)))
    ui.console.input("[dim]Нажмите Enter, чтобы вернуться в меню...[/]")


def main_menu(ui: UI) -> int | Command:
    """Главное меню -> 0 (начать работу), 1 (инструкция) или Command."""
    ui.screen()
    ui.explain(
        "Программа собирает сведения об объектах из нескольких таблиц Excel в одну.\n"
        "Введите номер пункта и нажмите Enter."
    )
    return ui.choose(
        "Главное меню",
        ["Начать работу", "Инструкция", "Выход"],
        allow_back=False,
    )
